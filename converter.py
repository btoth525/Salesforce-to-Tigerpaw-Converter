def build_csv(columns: list[str], rows: list[dict], options: Options | None = None) -> bytes:
    """Serialize rows to CSV bytes: CRLF, minimal or full quoting, optional BOM.

    With ``ascii_only`` the text is pure ASCII so the bytes read identically
    as UTF-8, Windows-1252 or ASCII — the BOM is the only non-ASCII byte and
    is kept by default because v1's BOM'd header is what Tigerpaw has been
    importing successfully.
    """
    options = options or Options()
    buf = io.StringIO()
    writer = csv.writer(
        buf,
        lineterminator="\r\n",
        quoting=csv.QUOTE_ALL if options.quote_all else csv.QUOTE_MINIMAL,
    )
    writer.writerow(columns)
    for row in rows:
        writer.writerow(["" if row.get(c) is None else str(row.get(c)) for c in columns])
    text = buf.getvalue()
    return text.encode("utf-8-sig" if options.bom else "utf-8")


def preview_payload(result: ConvertResult, filename: str, limit: int) -> dict:
    """Shape a :class:`ConvertResult` into the ``/api/preview`` JSON contract."""
    parse = result.parse
    changes = result.changes
    warnings = result.warnings
    return {
        "filename": filename,
        "rowCount": len(result.transformed_rows),
        "previewLimit": limit,
        "truncated": len(result.transformed_rows) > limit,
        "encoding": parse.encoding,
        "hadBom": parse.had_bom,
        "delimiter": parse.delimiter,
        "headerRowIndex": parse.header_row_index,
        "originalColumns": parse.original_columns,
        "transformedColumns": result.transformed_columns,
        "originalPreview": parse.rows[:limit],
        "transformedPreview": result.transformed_rows[:limit],
        "mapping": result.mapping_out,
        "aliasesUsed": parse.aliases_used,
        "addedColumns": result.added_columns,
        "droppedColumns": result.dropped_columns,
        "skippedRows": [s.to_dict() for s in parse.skipped],
        "changes": [c.to_dict() for c in changes[:MAX_LOG_ENTRIES]],
        "warnings": [w.to_dict() for w in warnings[:MAX_LOG_ENTRIES]],
        "changesTruncated": len(changes) > MAX_LOG_ENTRIES,
        "warningsTruncated": len(warnings) > MAX_LOG_ENTRIES,
        "options": result.options.to_dict(),
    }
